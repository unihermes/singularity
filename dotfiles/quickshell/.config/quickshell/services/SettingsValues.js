function clamp(key, value) {
    var bound = limits[key]
    if (!bound || typeof value !== "number" || !isFinite(value)) return undefined
    return Math.max(bound.min, Math.min(bound.max, Math.round(value)))
}

// Dynamic font and theme lists describe installed choices, not validity:
// a saved name must survive a temporarily missing font/theme package.
function stored(key, value) {
    if (choices[key] && choices[key].indexOf(value) === -1) return defaults[key]
    if (limits[key]) {
        var n = clamp(key, value)
        return n === undefined ? defaults[key] : n
    }
    return value
}
